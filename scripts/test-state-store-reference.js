'use strict';
const assert = require('assert/strict');
const { createSignageStore } = require('../architecture/reference/signage-store');
let checks = 0, writes = 0, calls = 0, errors = 0;
const validators = { agenda(value) {
    if (!value || Object.keys(value).some(k => !['days','enabled'].includes(k)) || !Array.isArray(value.days) || value.days.some(d => !['senin','selasa'].includes(d)) || typeof value.enabled !== 'boolean') throw new Error('Invalid agenda');
    return { days: [...new Set(value.days)], enabled: value.enabled };
} };
const store = createSignageStore({ validators, persist() { writes++; }, onError() { errors++; } });
const snapshot = (revision, days = ['senin']) => ({ schemaVersion: 1, domain: 'agenda', revision, mutationId: 'mutation-' + revision, payload: { days, enabled: false } });
const cached = snapshot(2);
assert.ok(store.hydrate(cached).applied); checks++;
assert.equal(writes, 0); checks++;
cached.payload.days.push('INVALID');
assert.deepEqual(store.get('agenda').snapshot.payload.days, ['senin']); checks++;
const unsubscribe = store.subscribe('agenda', () => { calls++; });
assert.ok(store.applyConfirmed(snapshot(2)).applied); checks++;
assert.equal(store.get('agenda').source, 'cloud'); checks++;
assert.equal(store.applyConfirmed(snapshot(1)).reason, 'stale-revision'); checks++;
assert.equal(store.applyConfirmed(snapshot(2)).reason, 'duplicate'); checks++;
assert.throws(() => store.applyConfirmed(snapshot(2, ['selasa'])), /conflicting/); checks++;
assert.ok(store.applyConfirmed(snapshot(3, [])).applied); checks++;
assert.deepEqual(store.get('agenda').snapshot.payload.days, []); checks++;
assert.equal(store.get('agenda').snapshot.payload.enabled, false); checks++;
assert.equal(store.hydrate(snapshot(10)).reason, 'cache-not-authoritative'); checks++;
assert.throws(() => store.get('agenda').snapshot.payload.days.push('senin'), TypeError); checks++;
assert.throws(() => store.applyConfirmed({ ...snapshot(4), schemaVersion: 99 }), /Invalid/); checks++;
assert.throws(() => store.applyConfirmed(snapshot(4, ['unknown'])), /Invalid/); checks++;
assert.throws(() => store.applyConfirmed({ ...snapshot(4), revision: NaN }), /Invalid/); checks++;
assert.throws(() => store.applyConfirmed({ ...snapshot(4), domain: '__proto__' }), /Invalid/); checks++;
assert.equal(calls, 2); checks++;
unsubscribe(); store.applyConfirmed(snapshot(4)); assert.equal(calls, 2); checks++;
const resilient = createSignageStore({ validators, persist() { throw new Error('Quota exceeded'); }, onError() { errors++; } });
let notified = false;
resilient.subscribe('agenda', () => { throw new Error('Broken renderer'); });
resilient.subscribe('agenda', () => { notified = true; });
assert.ok(resilient.applyConfirmed(snapshot(1)).applied); checks++;
assert.ok(notified && errors === 2); checks++;
assert.equal(resilient.get('agenda').source, 'cloud'); checks++;
const corruptCache = createSignageStore({ validators });
corruptCache.hydrate(snapshot(999));
assert.ok(corruptCache.applyConfirmed(snapshot(1)).applied); checks++;
assert.equal(corruptCache.get('agenda').snapshot.revision, 1); checks++;
assert.throws(() => store.applyConfirmed({ ...snapshot(5), payload: {days:[],enabled:false,unknown:1} }), /Invalid/); checks++;
console.log(`State store reference: ${checks} checks passed (not integrated into production)`);
